def get_docker_status() -> Dict[str, bool]:
    """Inspects running Docker Compose services for edge-iiot pipeline."""
    try:
        res = subprocess.run(
            ["docker", "compose", "ps", "--format", "{{.Service}}\t{{.State}}"],
            cwd=REPO_ROOT,
            capture_output=True, text=True, timeout=2
        )
        services = {}
        for line in res.stdout.strip().split("\n"):
            if line.strip():
                parts = line.strip().split("\t")
                if len(parts) == 2:
                    services[parts[0].strip()] = (parts[1].strip().lower() == "running")

        return {
            "producer_running": services.get("ids-producer", False),
            "inference_running": services.get("ids-inference", False),
            "redpanda_running": services.get("redpanda", False),
            "console_running": services.get("redpanda-console", False),
        }
    except Exception:
        return {
            "producer_running": False,
            "inference_running": False,
            "redpanda_running": False,
            "console_running": False,
        }


