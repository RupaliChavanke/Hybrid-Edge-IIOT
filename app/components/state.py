class DockerStreamMonitor:
    """
    Background subscriber thread consuming from Redpanda topics 'ids-predictions' and 'ids-alerts'.
    Enables Streamlit to monitor predictions generated by the Docker Compose pipeline in real-time.
    """
    _instance = None
    _lock = threading.Lock()

    @classmethod
    def get_instance(cls, brokers: Optional[str] = None):
        with cls._lock:
            if cls._instance is None:
                cls._instance = cls(brokers=brokers)
            return cls._instance

    def __init__(self, brokers: Optional[str] = None):
        self.brokers = brokers or os.getenv("REDPANDA_BROKERS", "localhost:19092")
        self.is_running = False
        self._stop_event = threading.Event()
        self.recent_predictions: deque = deque(maxlen=500)
        self.recent_alerts: deque = deque(maxlen=100)
        self.total_received = 0
        self.total_inferences = 0
        self.total_threats = 0
        self.total_benign = 0
        self.total_critical = 0
        self.total_high = 0
        self.total_alerts = 0
        self.attack_distribution: Dict[str, int] = {}
        self.latency_records: List[float] = []
        self.recent_timestamps: deque = deque(maxlen=200)
        self.thread: Optional[threading.Thread] = None
        self._initialized_history = False

    def start(self):
        if self.is_running or not HAS_CONFLUENT_KAFKA:
            return
        checker = RedpandaHealthChecker(self.brokers)
        if not checker.is_redpanda_available():
            return
        self.is_running = True
        self._stop_event.clear()
        self.thread = threading.Thread(target=self._worker, daemon=True)
        self.thread.start()

    def stop(self):
        self.is_running = False
        self._stop_event.set()
        if self.thread and self.thread.is_alive():
            self.thread.join(timeout=2)

    def _ingest_msg(self, topic: str, raw_str: str):
        try:
            data = json.loads(raw_str)
        except Exception:
            return

        if topic == "ids-predictions":
            self.total_received += 1
            self.total_inferences += 1
            self.recent_predictions.append(data)
            self.recent_timestamps.append(time.perf_counter())

            att = data.get("predicted_attack", "Normal")
            self.attack_distribution[att] = self.attack_distribution.get(att, 0) + 1

            risk = data.get("risk_level", "NORMAL")
            is_attack = (att.lower() != "normal")
            if is_attack:
                self.total_threats += 1
            else:
                self.total_benign += 1

            if risk == "CRITICAL":
                self.total_critical += 1
            elif risk == "HIGH":
                self.total_high += 1

            pipe_ms = data.get("latency_breakdown", {}).get("total_pipeline_ms", 1.4)
            self.latency_records.append(float(pipe_ms))
            if len(self.latency_records) > 1000:
                self.latency_records.pop(0)

        elif topic == "ids-alerts":
            self.total_alerts += 1
            self.recent_alerts.append(data)

    def _worker(self):
        conf = {
            "bootstrap.servers": self.brokers,
            "group.id": f"streamlit-ui-monitor-{uuid.uuid4().hex[:6]}",
            "auto.offset.reset": "latest",
            "enable.auto.commit": False,
            "session.timeout.ms": 6000
        }
        try:
            consumer = Consumer(conf)
            consumer.subscribe(["ids-predictions", "ids-alerts"])
        except Exception:
            self.is_running = False
            return

        # Pre-seed recent history on first startup
        if not self._initialized_history:
            try:
                for topic in ["ids-predictions", "ids-alerts"]:
                    tp = TopicPartition(topic, 0)
                    low, high = consumer.get_watermark_offsets(tp, timeout=1.0)
                    if high > low:
                        fetch_count = min(25, high - low)
                        tp.offset = high - fetch_count
                        consumer.assign([tp])
                        for _ in range(fetch_count):
                            msg = consumer.poll(timeout=0.2)
                            if msg and not msg.error():
                                self._ingest_msg(topic, msg.value().decode("utf-8"))
                consumer.subscribe(["ids-predictions", "ids-alerts"])
                self._initialized_history = True
            except Exception:
                pass

        while not self._stop_event.is_set():
            try:
                msg = consumer.poll(timeout=0.25)
                if msg is None:
                    continue
                if msg.error():
                    continue
                topic = msg.topic()
                payload = msg.value().decode("utf-8")
                self._ingest_msg(topic, payload)
            except Exception:
                time.sleep(0.1)

        try:
            consumer.close()
        except Exception:
            pass
        self.is_running = False

    def get_throughput(self) -> float:
        now = time.perf_counter()
        while self.recent_timestamps and (now - self.recent_timestamps[0]) > 4.0:
            self.recent_timestamps.popleft()
        if len(self.recent_timestamps) < 2:
            return 0.0
        dt = now - self.recent_timestamps[0]
        return round(float(len(self.recent_timestamps) / max(0.05, dt)), 1)

    def reset_stats(self):
        self.total_received = 0
        self.total_inferences = 0
        self.total_threats = 0
        self.total_benign = 0
        self.total_critical = 0
        self.total_high = 0
        self.total_alerts = 0
        self.attack_distribution.clear()
        self.latency_records.clear()
        self.recent_predictions.clear()
        self.recent_alerts.clear()
        self.recent_timestamps.clear()

    def get_stats(self) -> Dict[str, Any]:
        lats = self.latency_records if self.latency_records else [1.4]
        p99 = float(np.percentile(lats, 99)) if len(lats) > 5 else 1.4
        return {
            "status": "RUNNING" if self.is_running else "STOPPED",
            "messages_received": self.total_received,
            "messages_processed": self.total_inferences,
            "total_threats": self.total_threats,
            "total_benign": self.total_benign,
            "total_critical": self.total_critical,
            "total_high": self.total_high,
            "total_alerts": self.total_alerts,
            "attack_distribution": dict(self.attack_distribution),
            "p99_latency_ms": round(p99, 2),
            "messages_sec": self.get_throughput(),
            "consumer_lag": 0
        }


def init_session_state():
    """Initializes persistent streaming objects in Streamlit session state and reconnects to active daemons."""
    global _GLOBAL_PRODUCER, _GLOBAL_CONSUMER

    try:
        if "producer" not in st.session_state or st.session_state.producer is None:
            if _GLOBAL_PRODUCER is not None and _GLOBAL_PRODUCER.is_running:
                st.session_state.producer = _GLOBAL_PRODUCER
            else:
                st.session_state.producer = None

        if "consumer" not in st.session_state or st.session_state.consumer is None:
            if _GLOBAL_CONSUMER is not None and _GLOBAL_CONSUMER.is_running:
                st.session_state.consumer = _GLOBAL_CONSUMER
            else:
                st.session_state.consumer = None

        if "recent_predictions" not in st.session_state:
            st.session_state.recent_predictions = []
        if "recent_alerts" not in st.session_state:
            st.session_state.recent_alerts = []
        if "streaming_stats" not in st.session_state:
            st.session_state.streaming_stats = {
                "messages_sent": 0,
                "messages_processed": 0,
                "total_alerts": 0,
                "p99_latency_ms": 0.0,
                "throughput": 0.0
            }
    except Exception:
        pass


def get_producer() -> Optional[EdgeIIoTStreamingProducer]:
    """Returns the persistent streaming producer instance."""
    init_session_state()
    global _GLOBAL_PRODUCER
    if _GLOBAL_PRODUCER is not None and _GLOBAL_PRODUCER.is_running:
        return _GLOBAL_PRODUCER
    try:
        return st.session_state.get("producer")
    except Exception:
        return None


def get_consumer() -> Optional[EdgeIIoTStreamingConsumer]:
    """Returns the persistent streaming consumer instance."""
    init_session_state()
    global _GLOBAL_CONSUMER
    if _GLOBAL_CONSUMER is not None and _GLOBAL_CONSUMER.is_running:
        return _GLOBAL_CONSUMER
    try:
        return st.session_state.get("consumer")
    except Exception:
        return None


def start_producer(rate: float = 30.0, dataset_path: Optional[str] = None) -> EdgeIIoTStreamingProducer:
    """Initializes and starts the streaming producer."""
    global _GLOBAL_PRODUCER
    if dataset_path is None:
        p = REPO_ROOT / "data" / "samples" / "edge_iiot_sample.csv"
        dataset_path = str(p)

    if _GLOBAL_PRODUCER is None or not _GLOBAL_PRODUCER.is_running:
        _GLOBAL_PRODUCER = EdgeIIoTStreamingProducer(rate_msg_per_sec=rate, dataset_path=dataset_path)
        _GLOBAL_PRODUCER.start(loop_dataset=True)
    else:
        _GLOBAL_PRODUCER.rate_msg_per_sec = float(rate)
        if getattr(_GLOBAL_PRODUCER, "is_paused", False):
            _GLOBAL_PRODUCER.resume()

    try:
        st.session_state.producer = _GLOBAL_PRODUCER
    except Exception:
        pass
    return _GLOBAL_PRODUCER


def stop_producer():
    """Stops both local streaming producer and Docker producer container."""
    global _GLOBAL_PRODUCER
    if _GLOBAL_PRODUCER is not None:
        _GLOBAL_PRODUCER.stop()
        _GLOBAL_PRODUCER = None
    stop_docker_producer()
    try:
        if "producer" in st.session_state:
            st.session_state.producer = None
    except Exception:
        pass


def start_consumer(model_name: str = "Hybrid Ensemble") -> EdgeIIoTStreamingConsumer:
    """Initializes and starts the streaming inference consumer."""
    global _GLOBAL_CONSUMER
    if _GLOBAL_CONSUMER is None or not _GLOBAL_CONSUMER.is_running:
        _GLOBAL_CONSUMER = EdgeIIoTStreamingConsumer()
        _GLOBAL_CONSUMER.set_model(model_name)
        _GLOBAL_CONSUMER.start()
    else:
        _GLOBAL_CONSUMER.set_model(model_name)

    try:
        st.session_state.consumer = _GLOBAL_CONSUMER
    except Exception:
        pass
    return _GLOBAL_CONSUMER


def stop_consumer():
    """Stops both local streaming consumer and Docker inference container."""
    global _GLOBAL_CONSUMER
    if _GLOBAL_CONSUMER is not None:
        _GLOBAL_CONSUMER.stop()
        _GLOBAL_CONSUMER = None
    stop_docker_inference()
    try:
        if "consumer" in st.session_state:
            st.session_state.consumer = None
    except Exception:
        pass


def start_pipeline(rate: float = 30.0, model_name: str = "Hybrid Ensemble", prefer_docker: bool = False):
    """
    Starts full streaming pipeline.
    Synchronously initializes and returns (producer, consumer).
    If prefer_docker is True and Redpanda container is healthy, also starts Docker services and monitor.
    """
    d_status = get_docker_status()
    if prefer_docker and d_status["redpanda_running"]:
        start_docker_pipeline()
        monitor = DockerStreamMonitor.get_instance()
        monitor.start()

    cons = start_consumer(model_name=model_name)
    time.sleep(0.2)
    prod = start_producer(rate=rate)
    return prod, cons


def stop_pipeline():
    """Stops full pipeline across both Docker services and local background threads."""
    stop_docker_pipeline()
    stop_producer()
    stop_consumer()
    monitor = DockerStreamMonitor.get_instance()
    monitor.stop()


def reset_pipeline_stats():
    """Resets all live statistics and buffers across producer, consumer, monitor, and UI session."""
    cons = get_consumer()
    if cons:
        cons.reset_stats()
    prod = get_producer()
    if prod:
        prod.reset_stats()
    monitor = DockerStreamMonitor.get_instance()
    monitor.reset_stats()
    try:
        st.session_state.recent_predictions = []
        st.session_state.recent_alerts = []
    except Exception:
        pass


def get_active_predictions() -> List[Dict[str, Any]]:
    """Returns the most recent predictions from either in-process consumer or Docker stream monitor."""
    cons = get_consumer()
    if cons and cons.is_running and len(cons.recent_predictions) > 0:
        return list(reversed(cons.recent_predictions))

    monitor = DockerStreamMonitor.get_instance()
    if not monitor.is_running:
        monitor.start()
    if len(monitor.recent_predictions) > 0:
        return list(reversed(monitor.recent_predictions))

    try:
        return st.session_state.get("recent_predictions", [])
    except Exception:
        return []


