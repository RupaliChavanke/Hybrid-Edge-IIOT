def get_active_stream_stats() -> Dict[str, Any]:
    """Returns combined real-time statistics from active local consumer or Docker stream monitor."""
    cons = get_consumer()
    if cons and cons.is_running:
        return cons.get_stats()

    monitor = DockerStreamMonitor.get_instance()
    if not monitor.is_running:
        monitor.start()
    return monitor.get_stats()


def inject_single_sample_to_redpanda(sample_features: Dict[str, Any], ground_truth: Optional[str] = None) -> bool:
    """
    Publishes a single network sample directly to topic 'edge-iiot-raw' (via Redpanda or Cloud Bus).
    The background inference consumer will consume it, run inference, and publish the prediction.
    """
    from streaming.schemas import RawNetworkEvent
    brokers = os.getenv("REDPANDA_BROKERS", "localhost:19092")

    event = RawNetworkEvent(
        event_id=f"EVT-MANUAL-{uuid.uuid4().hex[:6].upper()}",
        sequence_id=999999,
        features=sample_features,
        dataset_label=ground_truth
    )
    payload = event.model_dump_json().encode("utf-8")

    checker = RedpandaHealthChecker(brokers)
    if checker.is_redpanda_available() and HAS_CONFLUENT_KAFKA:
        try:
            producer = Producer({"bootstrap.servers": brokers, "acks": 1})
            producer.produce("edge-iiot-raw", value=payload)
            producer.flush(timeout=3)
            return True
        except Exception:
            get_streaming_bus().publish("edge-iiot-raw", value=payload)
            return True
    else:
        get_streaming_bus().publish("edge-iiot-raw", value=payload)
        return True


_SAMPLE_DF = None

def inject_attack_type_sample(attack_type: str = "DDoS_UDP") -> bool:
    """Extracts a real packet of attack_type from Edge-IIoTset sample and injects it into edge-iiot-raw."""
    global _SAMPLE_DF
    import pandas as pd
    if _SAMPLE_DF is None:
        p = REPO_ROOT / "data" / "samples" / "edge_iiot_sample.csv"
        _SAMPLE_DF = pd.read_csv(p, nrows=10000, low_memory=False)

    matched = _SAMPLE_DF[_SAMPLE_DF["Attack_type"] == attack_type]
    if len(matched) > 0:
        row = matched.sample(1).iloc[0]
    else:
        row = _SAMPLE_DF.sample(1).iloc[0]

    features = {col: (val if pd.notnull(val) else None) for col, val in row.items() if col not in ["Attack_type", "Attack_label"]}
    gt = str(row.get("Attack_type", attack_type))
    return inject_single_sample_to_redpanda(sample_features=features, ground_truth=gt)
